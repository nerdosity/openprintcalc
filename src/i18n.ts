const DICTS: Record<Lang, Record<Key, string>> = { it: IT, en: EN };
const LOCALES: Record<Lang, string> = { it: 'it-IT', en: 'en-GB' };

/* ---------- configurazione corrente ---------- */

let lang: Lang = 'it';
let symbol = '€';

export const getLang = (): Lang => lang;
export function setLang(l: Lang): void {
  lang = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}
export function setSymbol(s: string): void { symbol = s.trim() || '€'; }
export const getSymbol = (): string => symbol;

/** 'auto' segue il browser: italiano -> it, altra lingua -> en, lingua assente -> it (default). */
export function resolveLang(
  setting: LangSetting,
  navLang: string | undefined = typeof navigator === 'undefined' ? undefined : navigator.language,
): Lang {
  if (setting !== 'auto') return setting;
  const n = (navLang ?? '').toLowerCase();
  return n === '' || n.startsWith('it') ? 'it' : 'en';
}

/**
 * Traduce `key`. Parametri `{x}` sostituiti; `{cur}` e' il simbolo valuta corrente.
 * Chiave mancante nella lingua scelta: si ripiega sull'italiano, poi sulla chiave stessa.
 */
export function t(key: Key, params: Readonly<Record<string, string | number>> = {}): string {
  const raw: string | undefined = DICTS[lang][key] || IT[key];
  const s = raw || key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : k === 'cur' ? symbol : m));
}
export const hasKey = (k: string): k is Key => k in IT;

/* ---------- numeri e valuta ---------- */

const nfCache = new Map<string, Intl.NumberFormat>();
function nf(opts: Intl.NumberFormatOptions): Intl.NumberFormat {
  const id = `${lang}|${JSON.stringify(opts)}`;
  let f = nfCache.get(id);
  if (!f) { f = new Intl.NumberFormat(LOCALES[lang], opts); nfCache.set(id, f); }
  return f;
}

/** Numero con al massimo `max` decimali (e almeno `min`), nel formato della lingua corrente. */
export const fmtNum = (v: unknown, max = 1, min = 0): string =>
  nf({ minimumFractionDigits: min, maximumFractionDigits: Math.max(min, max) }).format(Number(v));

/** Importo in valuta: separatori e posizione del simbolo seguono la lingua, il simbolo e' quello delle impostazioni. */
export function fmtCur(v: unknown): string {
  return nf({ style: 'currency', currency: 'EUR' }).formatToParts(Number(v))
    .map((p) => (p.type === 'currency' ? symbol : p.value)).join('');
}

/* ---------- DOM ---------- */

/** Applica il dizionario a `data-i18n` (testo), `data-i18n-html` (solo stringhe nostre) e `data-i18n-attr="attr:chiave;..."`. */
export function applyI18n(root: ParentNode = document): void {
  for (const e of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const k = e.dataset.i18n ?? '';
    if (hasKey(k)) e.textContent = t(k);
  }
  for (const e of root.querySelectorAll<HTMLElement>('[data-i18n-html]')) {
    const k = e.dataset.i18nHtml ?? '';
    if (hasKey(k)) e.innerHTML = t(k);
  }
  for (const e of root.querySelectorAll<HTMLElement>('[data-i18n-attr]')) {
    for (const pair of (e.dataset.i18nAttr ?? '').split(';')) {
      const [attr, k] = pair.split(':').map((x) => x.trim());
      if (attr && k && hasKey(k)) e.setAttribute(attr, t(k));
    }
  }
}
