// Rileva lo slicer da un G-code ASCII e ne estrae statistiche e config.
import { extract, parseComments, parseTime } from '../gcode.ts';
import type { KV } from '../types.ts';
import { emptyPrint } from './types.ts';
import type { ParsedPrint, SlicerId } from './types.ts';


export interface GcodeTextOptions {
  /** Cura: densita' del filamento in g/cm3 (default 1.24) */
  density?: number;
  /** Cura: diametro del filamento in mm (default 1.75) */
  diameter?: number;
}

export function detectSlicer(text: string): SlicerId {
  const head = text.slice(0, 8000);
  if (/^;\s*generated by PrusaSlicer/im.test(head)) return 'prusaslicer';
  if (/^;\s*generated by OrcaSlicer/im.test(head)) return 'orcaslicer';
  if (/^;\s*BambuStudio/im.test(head) || /^;\s*HEADER_BLOCK_START/m.test(head)) return 'bambustudio';
  if (/^;FLAVOR:/m.test(head) || /^;Generated with Cura/im.test(head)) return 'cura';
  return 'unknown';
}

const num = (v: unknown): number | null => { const x = parseFloat(String(v ?? '')); return Number.isFinite(x) ? x : null; };
const list = (v: string | undefined): number[] =>
  (v ?? '').split(/[,;]/).map((s) => parseFloat(s)).filter((x) => Number.isFinite(x));
const sum = (a: number[]): number => a.reduce((x, y) => x + y, 0);
const firstId = (v: string): string => (v.split(';')[0] ?? '').replace(/^"|"$/g, '').trim();

/** Prima occorrenza di "; label : valore" (formato Bambu, con i due punti). */
function colonValue(text: string, label: string): string | undefined {
  const esc = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`^;\\s*${esc}\\s*:\\s*(.*?)\\s*$`, 'm').exec(text)?.[1];
}

function fromData(slicer: SlicerId, kv: KV): ParsedPrint {
  const d = extract(kv);
  const r = emptyPrint(slicer);
  r.grams = d.grams; r.hours = d.hours;
  r.printerModel = d.printerModel; r.printerSettingsId = d.printerSettingsId;
  r.filamentSettingsId = kv.filament_settings_id ? firstId(kv.filament_settings_id) : null;
  r.filamentType = d.filamentType; r.filamentCost = d.filamentCost; r.filamentDensity = d.density;
  r.nozzleDiameter = d.nozzleDiameter; r.nozzleTemp = d.nozzleTemp; r.bedTemp = d.bedTemp;
  r.params = d.params;
  return r;
}

function parsePrusa(kv: KV, slicer: SlicerId): ParsedPrint {
  const r = fromData(slicer, kv);
  r.perExtruderGrams = list(kv['filament used [g]']);
  r.wasteGrams = num(kv['total filament used for wipe tower [g]']);
  r.toolChanges = num(kv['total toolchanges']);
  if (r.toolChanges === null && r.wasteGrams !== null) r.toolChanges = 0;
  return r;
}

function parseBambuOrca(text: string, kv: KV, slicer: SlicerId): ParsedPrint {
  const r = fromData(slicer, kv);
  // tempo: "model printing time: X; total estimated time: Y" (si usa il totale)
  const tl = /^;\s*model printing time:\s*([^;]*?)\s*;\s*total estimated time:\s*(.*?)\s*$/m.exec(text);
  const secs = tl ? (parseTime(tl[2]) ?? parseTime(tl[1])) : null;
  if (secs !== null) r.hours = secs / 3600;
  const weights = list(colonValue(text, 'total filament weight [g]'));
  const used = list(kv['filament used [g]']);
  const dens = list(kv.filament_density ?? colonValue(text, 'filament_density'));
  r.perExtruderGrams = used.length ? used : weights;
  if (weights.length) r.grams = sum(weights);
  else if (used.length) r.grams = sum(used);
  else {
    // senza peso: grammi dalla lunghezza (mm) x area del filamento x densita
    const lens = list(colonValue(text, 'total filament length [mm]') ?? kv['filament used [mm]']);
    const diam = list(kv.filament_diameter ?? colonValue(text, 'filament_diameter'));
    if (lens.length) {
      r.perExtruderGrams = lens.map((mm, i) => mm * Math.PI * ((diam[i] ?? diam[0] ?? 1.75) / 2) ** 2 * (dens[i] ?? dens[0] ?? 1.24) / 1000);
      r.grams = sum(r.perExtruderGrams);
      r.warnings.push({ key: 'warn.gramsFromLength' });
    }
  }
  if (r.filamentDensity === null && dens.length) r.filamentDensity = dens[0] ?? null;
  // il peso di Bambu/Orca include gia' lo spurgo: nessuna stima di scarto
  r.toolChanges = num(colonValue(text, 'total filament change') ?? kv['total filament change']);
  if (r.grams === null) r.warnings.push({ key: 'warn.noWeight' });
  return r;
}

function parseCura(text: string, opts: GcodeTextOptions): ParsedPrint {
  const r = emptyPrint('cura');
  const time = /^;TIME:\s*(\d+(?:\.\d+)?)/m.exec(text)?.[1];
  if (time) r.hours = parseFloat(time) / 3600;
  const fu = /^;Filament used:\s*(.+)$/m.exec(text)?.[1];
  const density = opts.density && opts.density > 0 ? opts.density : 1.24;
  const diameter = opts.diameter && opts.diameter > 0 ? opts.diameter : 1.75;
  if (fu) {
    if (/mm3/.test(fu)) {
      r.perExtruderGrams = list(fu).map((mm3) => mm3 / 1000 * density);
    } else {
      const area = Math.PI * (diameter / 2) ** 2; // mm2
      r.perExtruderGrams = fu.split(',').map((s) => parseFloat(s) * 1000 * area / 1000 * density).filter((x) => Number.isFinite(x));
    }
    r.grams = sum(r.perExtruderGrams);
    r.filamentDensity = density;
    r.warnings.push({ key: 'warn.curaGrams', params: { d: diameter, rho: density } });
  } else r.warnings.push({ key: 'warn.curaNoFilament' });
  const lh = num(/^;Layer height:\s*(.+)$/m.exec(text)?.[1]);
  if (lh !== null) r.params = { perimeters: null, topSolidLayers: null, bottomSolidLayers: null, fillDensity: null, layerHeight: lh, widths: {} };
  const mat = /^;MATERIAL:\s*(.+)$/m.exec(text)?.[1]?.trim();
  if (mat && Number.isNaN(Number(mat))) r.filamentType = mat;
  return r;
}

export function parseGcodeText(text: string, opts: GcodeTextOptions = {}): ParsedPrint {
  const slicer = detectSlicer(text);
  if (slicer === 'cura') return parseCura(text, opts);
  const kv = parseComments(text);
  if (slicer === 'bambustudio' || slicer === 'orcaslicer') return parseBambuOrca(text, kv, slicer);
  const r = parsePrusa(kv, slicer);
  if (slicer === 'unknown') {
    r.warnings.push({ key: 'warn.unknownSlicer' });
    if (r.grams === null && r.hours === null) r.warnings.push({ key: 'warn.noData' });
  }
  return r;
}
